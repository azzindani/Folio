#!/usr/bin/env node
// Variant generator. For each hand-crafted base template under
// src/templates/builtin/, emit one variant per theme that the base
// doesn't already declare. Multiplies a curated set of ~60 base
// layouts into ~800 distinct catalog entries.
//
// Run via `npm run gen:variants` or it's wired into `npm run build`.
//
// Variants are deterministic and idempotent — re-running with no base
// changes produces zero file writes, so git diffs stay clean.

import { promises as fs } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { load as parseYAML, dump as dumpYAML } from 'js-yaml';

const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);
const ROOT       = path.resolve(__dirname, '..');
const TPL_DIR    = path.join(ROOT, 'src', 'templates', 'builtin');

// Variant filename prefix. Anything matching `v-*.template.yaml` is a
// generated variant and is rewritten by this script. Sorts after the
// numbered hand-crafted originals (`01-...`, `02-...`, etc.) so the
// directory stays readable.
const VARIANT_PREFIX = 'v-';

const ALL_THEMES = [
  { id: 'dark-tech',       name: 'Dark Tech' },
  { id: 'light-clean',     name: 'Light Clean' },
  { id: 'ocean-blue',      name: 'Ocean Blue' },
  { id: 'neon-bloom',      name: 'Neon Bloom' },
  { id: 'indigo-pro',      name: 'Indigo Pro' },
  { id: 'sunset-glow',     name: 'Sunset Glow' },
  { id: 'mono-print',      name: 'Mono Print' },
  { id: 'forest-deep',     name: 'Forest Deep' },
  { id: 'pastel-dream',    name: 'Pastel Dream' },
  { id: 'high-contrast',   name: 'High Contrast' },
  { id: 'brutalist-mono',  name: 'Brutalist Mono' },
  { id: 'cyber-synthwave', name: 'Cyber Synthwave' },
  { id: 'editorial-cream', name: 'Editorial Cream' },
  { id: 'corporate-slate', name: 'Corporate Slate' },
];

/** True for files like `01-simple-poster.template.yaml`, not `v-...`. */
function isBaseTemplate(name) {
  return name.endsWith('.template.yaml') && !name.startsWith(VARIANT_PREFIX);
}

function variantFilename(baseSlug, themeId) {
  return `${VARIANT_PREFIX}${baseSlug}-${themeId}.template.yaml`;
}

/** Derive a clean slug from the base meta.id (strip `tmpl-` prefix). */
function slugFromId(metaId) {
  return String(metaId).replace(/^tmpl-/, '');
}

function variantHeader(baseFile, themeId) {
  return [
    '# Generated by scripts/gen-template-variants.mjs — DO NOT EDIT.',
    `# Source: ${baseFile}`,
    `# Variant axis: theme=${themeId}`,
    '',
  ].join('\n');
}

/** Build a variant TemplateSpec from a base + theme. */
function buildVariant(base, theme, baseFile) {
  // Clone — JSON round-trip is sufficient since YAML data is plain.
  const v = JSON.parse(JSON.stringify(base));
  const baseId   = base.meta?.id ?? path.basename(baseFile, '.template.yaml');
  const baseName = base.meta?.name ?? baseId;
  const slug     = slugFromId(baseId);

  v.meta = v.meta ?? {};
  v.meta.id   = `tmpl-${slug}-theme-${theme.id}`;
  v.meta.name = `${baseName} — ${theme.name}`;
  v.theme     = { ref: theme.id };

  const existingTags = Array.isArray(v.meta.tags) ? v.meta.tags : [];
  v.meta.tags = [...new Set([...existingTags, 'generated', `theme-${theme.id}`])];

  // Track provenance so future tooling can find the source.
  v.meta.generated_from = path.basename(baseFile);
  v.meta.generator      = 'gen-template-variants.mjs';

  return v;
}

async function readBase(file) {
  const raw  = await fs.readFile(path.join(TPL_DIR, file), 'utf8');
  const spec = parseYAML(raw);
  if (!spec || spec._protocol !== 'template/v1') return null;
  return spec;
}

/**
 * Delete stale variant files whose source base no longer exists,
 * so renaming/removing a base also drops its derived variants.
 */
async function pruneStaleVariants(liveVariantFiles) {
  const allFiles = await fs.readdir(TPL_DIR);
  const wanted = new Set(liveVariantFiles);
  let pruned = 0;
  for (const f of allFiles) {
    if (!f.startsWith(VARIANT_PREFIX)) continue;
    if (wanted.has(f)) continue;
    await fs.unlink(path.join(TPL_DIR, f));
    pruned++;
  }
  return pruned;
}

export async function generateVariants({ silent = false } = {}) {
  const files = (await fs.readdir(TPL_DIR)).filter(isBaseTemplate).sort();
  const written  = [];
  const unchanged = [];
  const errors   = [];

  for (const baseFile of files) {
    let base;
    try {
      base = await readBase(baseFile);
    } catch (err) {
      errors.push(`${baseFile}: ${err.message}`);
      continue;
    }
    if (!base) continue;
    const originalTheme = base.theme?.ref;

    for (const theme of ALL_THEMES) {
      if (theme.id === originalTheme) continue;
      const out = buildVariant(base, theme, baseFile);
      const outName = variantFilename(slugFromId(base.meta.id), theme.id);
      const yaml = variantHeader(baseFile, theme.id) + dumpYAML(out, { lineWidth: 200 });
      const outPath = path.join(TPL_DIR, outName);

      let prev = '';
      try { prev = await fs.readFile(outPath, 'utf8'); } catch { /* new file */ }
      if (prev === yaml) {
        unchanged.push(outName);
      } else {
        await fs.writeFile(outPath, yaml, 'utf8');
        written.push(outName);
      }
    }
  }

  // Prune variants whose base no longer exists.
  const liveSet = [...written, ...unchanged];
  const pruned  = await pruneStaleVariants(liveSet);

  if (!silent) {
    console.log(
      `[gen-variants] bases=${files.length}  variants=${liveSet.length}  ` +
      `wrote=${written.length}  unchanged=${unchanged.length}  pruned=${pruned}`,
    );
    if (errors.length) {
      console.error(`[gen-variants] ${errors.length} error(s):`);
      for (const e of errors) console.error(`  - ${e}`);
    }
  }

  return { written: written.length, unchanged: unchanged.length, pruned, errors };
}

// ── CLI entry ──────────────────────────────────────────────────

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isCli) {
  generateVariants().then(({ errors }) => {
    if (errors.length) process.exitCode = 1;
  }).catch(err => {
    console.error('[gen-variants] fatal:', err);
    process.exit(1);
  });
}
